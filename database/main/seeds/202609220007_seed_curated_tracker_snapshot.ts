const seed: SeedDefinition = defineSeed({
  name: '202609220007_seed_curated_tracker_snapshot',

  async run({ query }) {
    await query.deleteFrom('problemComments').allowAllRows().execute();
    await query.deleteFrom('problemActivities').allowAllRows().execute();
    await query.deleteFrom('issues').allowAllRows().execute();
    await query.deleteFrom('featurePoints').allowAllRows().execute();

    const idByName = new Map<string, number>();
    const insertFeature = async (feature: FeatureSeed): Promise<void> => {
      const parentId =
        feature.level === 'dimension'
          ? null
          : (idByName.get(feature.dimension ?? '') ?? null);
      if (feature.level === 'feature' && parentId === null) {
        throw new Error(`Snapshot parent is missing: ${feature.name}`);
      }
      const result = await query
        .insertInto('featurePoints')
        .values({
          name: feature.name,
          level: feature.level,
          parentId,
          owner: feature.owner,
          skillsStatus: feature.skillsStatus,
          docsStatus: feature.docsStatus,
          exampleExists: feature.exampleExists,
          exampleExpected: feature.exampleExpected,
          exampleCurrent: feature.exampleCurrent,
          status: feature.status,
          designScore: feature.designScore,
          designNote: feature.designNote,
          developmentScore: feature.developmentScore,
          developmentNote: feature.developmentNote,
          agentFriendlinessScore: feature.agentFriendlinessScore,
          agentFriendlinessNote: feature.agentFriendlinessNote,
          outputQualityScore: feature.outputQualityScore,
          outputQualityNote: feature.outputQualityNote,
          remark: feature.remark,
          sortOrder: feature.sortOrder,
          createdAt: new Date(),
          updatedAt: new Date(),
        })
        .execute();
      idByName.set(feature.name, Number(result.insertId));
    };

    for (const feature of FEATURES) {
      if (feature.level === 'dimension') await insertFeature(feature);
    }
    for (const feature of FEATURES) {
      if (feature.level === 'feature') await insertFeature(feature);
    }

    const problemIdByKey = new Map<string, number>();
    for (const problem of PROBLEMS) {
      const featurePointId = idByName.get(problem.feature);
      if (featurePointId === undefined) {
        throw new Error(`Snapshot feature point is missing: ${problem.feature}`);
      }
      const result = await query
        .insertInto('issues')
        .values({
          title: problem.title,
          description: problem.description,
          featurePointId,
          type: problem.type,
          status: problem.status,
          owner: problem.owner,
          createdAt: new Date(problem.createdAt),
          updatedAt: new Date(problem.updatedAt),
        })
        .execute();
      problemIdByKey.set(
        `${problem.feature}::${problem.title}`,
        Number(result.insertId),
      );
    }

    for (const activity of ACTIVITIES) {
      const problemId = problemIdByKey.get(
        `${activity.feature}::${activity.problemTitle}`,
      );
      if (problemId === undefined) continue;
      await query
        .insertInto('problemActivities')
        .values({
          problemId,
          // Actor ids belong to the database this snapshot came from; the name is
          // what the timeline displays, so it is carried without a foreign id.
          actorId: null,
          actorName: activity.actorName,
          kind: activity.kind,
          fromStatus: activity.fromStatus,
          toStatus: activity.toStatus,
          createdAt: new Date(activity.createdAt),
        })
        .execute();
    }
  },
});

export default seed;
