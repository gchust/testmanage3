/**
 * Curated tracker snapshot: the checklist the team works from today.
 *
 * The first import seeds carried the raw workbook; this snapshot is the curated
 * state that replaced it (readiness judgements, the Example acceptance rewrite,
 * owners, statuses and timeline). It runs once per database. On the deployment it
 * was added for it replaces what the earlier release had; on a fresh install it
 * seeds this dataset;  a database that already ran it keeps its own edits.
 *
 * Deliberately destructive on its first run: delete the tracker rows, then write
 * the snapshot. The legacy `missing_items` table is left untouched — the
 * application no longer reads it.
 */
