// Public protocol snapshot: gchust/nb3-factory@ff7e1e1. No factory runtime dependency.
import { readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
const config = await resolveConfig(new URL('../package.json', import.meta.url));
const dir = new URL(
  '../server/providers/evaluations/contracts/',
  import.meta.url,
);
for (const name of ['Report', 'Batch', 'Bundle', 'Receipt']) {
  const schema = JSON.parse(
    readFileSync(
      new URL('evaluation-' + name.toLowerCase() + '.v1.schema.json', dir),
      'utf8',
    ),
  );
  function type(s) {
    if (s.$ref) return name + '_' + s.$ref.split('/').at(-1);
    if ('const' in s) return JSON.stringify(s.const);
    if (s.enum) return s.enum.map((x) => JSON.stringify(x)).join(' | ');
    if (!s.properties && (s.anyOf || s.oneOf))
      return (s.anyOf || s.oneOf).map(type).join(' | ');
    if (s.allOf) return s.allOf.map(type).join(' & ');
    if (Array.isArray(s.type))
      return s.type.map((t) => type({ ...s, type: t })).join(' | ');
    if (s.type === 'object' || s.properties) {
      const fields = Object.entries(s.properties || {}).map(
        ([k, v]) =>
          JSON.stringify(k) +
          (s.required?.includes(k) ? '' : '?') +
          ': ' +
          type(v) +
          ';',
      );
      if (s.additionalProperties !== false)
        fields.push(
          '[key: string]: ' +
            (typeof s.additionalProperties === 'object'
              ? type(s.additionalProperties)
              : 'unknown') +
            ';',
        );
      return '{ ' + fields.join(' ') + ' }';
    }
    if (s.type === 'array') return 'Array<' + type(s.items || {}) + '>';
    if (s.type === 'integer' || s.type === 'number') return 'number';
    if (['string', 'boolean', 'null'].includes(s.type)) return s.type;
    return 'unknown';
  }
  const lines = [
    '// Generated by scripts/generate-evaluation-contracts.mjs from the pinned public schema.',
  ];
  for (const [key, value] of Object.entries(schema.$defs || {}))
    lines.push('export type ' + name + '_' + key + ' = ' + type(value) + ';');
  lines.push('export type Evaluation' + name + ' = ' + type(schema) + ';');
  writeFileSync(
    new URL(name.toLowerCase() + '.ts', dir),
    await format(lines.join('\n') + '\n', {
      ...config,
      singleQuote: true,
      parser: 'typescript',
    }),
  );
}
